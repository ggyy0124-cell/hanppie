"""Merge the C++ SDK into one header for single-file builds.

Dev-C++ and online judges compile one source file with fixed options and no
extra link flags, so the SDK ships as ``hanppie.h``: every public and internal
header in dependency order followed by every source file. Include it from
exactly one ``.cpp`` file.

    python3 cpp/tools/amalgamate.py cpp/build/hanppie.h
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

__all__: list[str] = []

ROOT = Path(__file__).resolve().parent.parent
INCLUDE_DIR = ROOT / "include"
SOURCE_DIR = ROOT / "src"
LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')
VERSION = re.compile(r'^#define HANPPIE_VERSION "([0-9.]+)"$', re.MULTILINE)


def resolve(name: str, including: Path) -> Path:
    for base in (including.parent, INCLUDE_DIR, SOURCE_DIR):
        candidate = base / name
        if candidate.is_file():
            return candidate.resolve()
    raise FileNotFoundError(f"{including.relative_to(ROOT)}: cannot resolve {name}")


def emit(path: Path, seen: set[Path], out: list[str]) -> None:
    if path in seen:
        return
    seen.add(path)
    body: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = LOCAL_INCLUDE.match(line)
        if match:
            emit(resolve(match.group(1), path), seen, out)
            continue
        body.append(line)
    out.append(f"// ---- {path.relative_to(ROOT).as_posix()} ----")
    out.extend(body)
    out.append("")


def amalgamate() -> str:
    umbrella = INCLUDE_DIR / "hanppie" / "hanppie.hpp"
    match = VERSION.search(umbrella.read_text(encoding="utf-8"))
    if match is None:
        raise ValueError("HANPPIE_VERSION not found in hanppie.hpp")
    out = [
        f"// Hanppie C++ SDK {match.group(1)}, single-header build.",
        "// Generated by cpp/tools/amalgamate.py from"
        " https://github.com/ggyy0124-cell/hanppie (Apache-2.0); do not edit.",
        "// Include this file from exactly one .cpp file; it contains the implementation.",
        "#ifndef HANPPIE_SINGLE_HEADER_H",
        "#define HANPPIE_SINGLE_HEADER_H",
        "",
    ]
    seen: set[Path] = set()
    emit(umbrella.resolve(), seen, out)
    for source in sorted(SOURCE_DIR.glob("*.cpp")):
        emit(source.resolve(), seen, out)
    out.append("#endif  // HANPPIE_SINGLE_HEADER_H")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"usage: {argv[0]} <output.h>", file=sys.stderr)
        return 2
    output = Path(argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(amalgamate(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
